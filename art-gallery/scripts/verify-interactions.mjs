import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base=process.env.TEST_URL||'http://localhost:3000';
const browser=await chromium.launch();
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000},colorScheme:'dark'});
 await context.addInitScript(()=>localStorage.setItem('popart-theme','dark'));
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 for(const locale of ['en','fr']) {
  await page.goto(`${base}/${locale}`,{waitUntil:'load'});
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  assert.equal(await page.locator('.theme-control').count(),0);
  assert.equal(await page.locator('body').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(251, 252, 253)');
  assert.equal(await page.locator('footer').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(251, 252, 253)');
  assert((await page.locator('header img').getAttribute('src')).includes('new-logo.png'));
  const hero=page.locator('main section').first();
  assert.equal(await hero.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(237, 242, 250)');
  const nav=page.locator('.desktop-navigation a').nth(1);
  await nav.hover();
  await page.waitForTimeout(250);
  assert.equal(await nav.evaluate(el=>getComputedStyle(el,'::before').content),'none');
  assert.equal(await nav.evaluate(el=>getComputedStyle(el).color),'rgb(23, 36, 51)');
  assert.equal(await page.locator('html').evaluate(el=>getComputedStyle(el).scrollbarColor),'rgb(36, 73, 164) rgb(251, 252, 253)');
  assert.equal(await page.locator('.packages').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(237, 241, 247)');
  const poster=page.locator('.brand-study');
  const remix=page.locator('.remix-control');
  await remix.click();assert.equal(await poster.getAttribute('data-variation'),'1');
  await remix.focus();await page.keyboard.press('Enter');assert.equal(await poster.getAttribute('data-variation'),'2');
  await page.keyboard.press('Space');assert.equal(await poster.getAttribute('data-variation'),'0');
  const surface=page.locator('.poster-playground');
  await surface.hover({position:{x:100,y:100}});
  await page.waitForFunction(()=>document.querySelector('.poster-playground').dataset.pointerActive==='true');
  assert.notEqual(await surface.evaluate(el=>el.style.getPropertyValue('--drift-x')),'');
  const image=page.locator('#featured-work .project-image-surface').first();
  await image.hover({position:{x:180,y:150}});
  await page.waitForTimeout(250);
  assert.equal(await image.locator('.project-pointer-label').evaluate(el=>getComputedStyle(el).opacity),'1');
  await page.mouse.move(0,0);assert.equal(await image.getAttribute('data-pointer-active'),null);
  await page.locator('#featured-work .project-card-preview').first().click();
  const modal=page.getByRole('dialog');await modal.waitFor();
  assert.equal(await modal.evaluate(el=>getComputedStyle(el).getPropertyValue('--background').trim()),'#fbfcfd');
  await page.keyboard.press('Escape');
  const eye=page.locator('footer button');await eye.scrollIntoViewIfNeeded();await eye.click();
  assert.equal(await eye.getAttribute('aria-pressed'),'true');
  assert((await eye.locator('img').getAttribute('src')).includes('new-logo.png'));
 }
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.locator('.poster-playground').hover();
 assert.equal(await page.locator('.poster-disc').evaluate(el=>getComputedStyle(el).animationName),'none');
 await page.locator('#featured-work .project-image-surface').first().hover();
 assert.equal(await page.locator('.project-pointer-label').first().evaluate(el=>getComputedStyle(el).display),'none');
 await page.setViewportSize({width:1440,height:1000});
 await page.locator('body').click({position:{x:5,y:5},force:true});
 await page.screenshot({path:'.animation-review/light-only-desktop.png',fullPage:true});
 const touch=await browser.newContext({isMobile:true,hasTouch:true,viewport:{width:375,height:812},colorScheme:'dark'});
 const mobile=await touch.newPage();await mobile.goto(`${base}/en`,{waitUntil:'load'});
 await mobile.locator('.remix-control').tap();
 assert.equal(await mobile.locator('.brand-study').getAttribute('data-variation'),'1');
 assert.equal(await mobile.locator('.poster-playground').getAttribute('data-pointer-active'),null);
 assert(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await mobile.screenshot({path:'.animation-review/light-only-mobile.png',fullPage:true});
 await touch.close();
 assert.deepEqual(errors,[]);
 console.log('PASS bright opening, restrained navigation, branded scrollbar, gallery palette; light-only UI ignores stale dark preference; supplied logos; bilingual pointer, remix and keyboard interactions; light lightbox; footer; reduced motion; mobile tap; no browser errors');
} finally {await browser.close();}
